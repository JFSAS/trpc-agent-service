    row('模拟 IM', tint(CHANNEL_LAB_URL, '36'))
    row('Gateway 管理', tint('http://127.0.0.1:' + str(values.get('GATEWAY_ADMIN_PORT', '29091')), '36'))
    print()
    row('租户账号', tint(_pad(str(owner.get('username', '(见凭据文件)')), 14), '1') + '评测建议使用')
    row('租户密码', tint(str(owner.get('password', '(见凭据文件)')), '1'))
    row('管理员账号', tint(_pad(str(admin.get('username', '(见凭据文件)')), 14), '1') + '平台管理')
